class GitHubClient:
    def __init__(self, base_url: str = "https://api.github.com", timeout: float = 10.0):
        self.base_url = base_url.rstrip("/")
        self.timeout = timeout

    def _get_headers(self, token: Optional[str] = None) -> Dict[str, str]:
        headers = {
            "Accept": "application/vnd.github+json",
            "User-Agent": "GitAuto-Automation-Engine/1.0",
            "X-GitHub-Api-Version": "2022-11-28",
        }
        if token:
            headers["Authorization"] = f"Bearer {token}"
        return headers

    def _extract_rate_limits(self, response: httpx.Response) -> Dict[str, Any]:
        remaining = response.headers.get("x-ratelimit-remaining")
        limit = response.headers.get("x-ratelimit-limit")
        reset = response.headers.get("x-ratelimit-reset")
        reset_iso = None
        if reset and reset.isdigit():
            reset_iso = datetime.fromtimestamp(int(reset), tz=timezone.utc).isoformat()
        return {
            "remaining": int(remaining) if remaining and remaining.isdigit() else 5000,
            "limit": int(limit) if limit and limit.isdigit() else 5000,
            "reset_at": reset_iso,
        }

    async def exchange_oauth_code(
        self, code: str, code_verifier: str, redirect_uri: Optional[str] = None
    ) -> Dict[str, Any]:
        """Exchanges OAuth authorization code + PKCE code_verifier for access token."""
        url = "https://github.com/login/oauth/access_token"
        payload = {
            "client_id": settings.GITHUB_CLIENT_ID,
            "client_secret": settings.GITHUB_CLIENT_SECRET,
            "code": code,
            "redirect_uri": redirect_uri or settings.GITHUB_REDIRECT_URI,
            "code_verifier": code_verifier,
        }
        headers = {
            "Accept": "application/json",
            "User-Agent": "GitAuto-OAuth/1.0",
        }
        async with httpx.AsyncClient(timeout=self.timeout) as client:
            resp = await client.post(url, json=payload, headers=headers)
            if resp.status_code != 200:
                raise GitHubApiException(resp.status_code, f"OAuth token exchange failed: {resp.text}")
            data = resp.json()
            if "error" in data:
                raise GitHubApiException(
                    400,
                    f"OAuth error: {data.get('error_description', data['error'])}",
                    details=data,
                )
            return data

    async def get_user_profile(self, token: str) -> Dict[str, Any]:
        """Fetches the authenticated user profile."""
        url = f"{self.base_url}/user"
        async with httpx.AsyncClient(timeout=self.timeout) as client:
            resp = await client.get(url, headers=self._get_headers(token))
            if resp.status_code == 401:
                raise UnauthorizedException("GitHub access token is invalid or expired.")
            if resp.status_code != 200:
                raise GitHubApiException(resp.status_code, resp.text)
            return resp.json()

    async def check_rate_limit(self, token: str) -> Dict[str, Any]:
        """Retrieves current rate limit status."""
        url = f"{self.base_url}/rate_limit"
        async with httpx.AsyncClient(timeout=self.timeout) as client:
            resp = await client.get(url, headers=self._get_headers(token))
            if resp.status_code == 401:
                raise UnauthorizedException("GitHub token expired.")
            if resp.status_code != 200:
                return {"remaining": 5000, "limit": 5000, "reset_at": None}
            data = resp.json()
            core = data.get("resources", {}).get("core", {})
            reset = core.get("reset")
            reset_iso = datetime.fromtimestamp(reset, tz=timezone.utc).isoformat() if reset else None
            return {
                "remaining": core.get("remaining", 5000),
                "limit": core.get("limit", 5000),
                "reset_at": reset_iso,
            }

    async def create_repository(
        self,
        token: str,
        name: str,
        description: Optional[str] = "",
        private: bool = True,
        auto_init: bool = False,
    ) -> Tuple[Dict[str, Any], int]:
        """Creates a new repository under the authenticated user's account."""
        url = f"{self.base_url}/user/repos"
        payload = {
            "name": name,
            "description": description or "",
            "private": private,
            "auto_init": auto_init,
            "has_issues": True,
            "has_projects": False,
            "has_wiki": False,
        }
        async with httpx.AsyncClient(timeout=self.timeout) as client:
            resp = await client.post(url, json=payload, headers=self._get_headers(token))
            if resp.status_code == 422:
                # Name collision or validation failure
                err_data = resp.json()
                msg = err_data.get("message", "Repository already exists or name invalid")
                raise RepositoryConflictException(name)
            if resp.status_code == 401:
                raise UnauthorizedException("GitHub token expired.")
            if resp.status_code == 403 and "rate limit" in resp.text.lower():
                limits = self._extract_rate_limits(resp)
                raise RateLimitExceededException(reset_at=limits.get("reset_at"))
            if resp.status_code != 201:
                raise GitHubApiException(resp.status_code, f"Failed to create repository: {resp.text}")
            return resp.json(), resp.status_code

    async def get_repository(self, token: str, owner: str, repo: str) -> Optional[Dict[str, Any]]:
        """Gets repository metadata."""
        url = f"{self.base_url}/repos/{owner}/{repo}"
        async with httpx.AsyncClient(timeout=self.timeout) as client:
            resp = await client.get(url, headers=self._get_headers(token))
            if resp.status_code == 404:
                return None
            if resp.status_code == 401:
                raise UnauthorizedException("GitHub token expired.")
            if resp.status_code != 200:
                raise GitHubApiException(resp.status_code, resp.text)
            return resp.json()

    async def put_file_content(
        self,
        token: str,
        owner: str,
        repo: str,
        path: str,
        content: str,
        commit_message: str,
        branch: str = "main",
        sha: Optional[str] = None,
    ) -> Tuple[Dict[str, Any], int]:
        """Creates or updates a file in the repository using the GitHub Contents API."""
        url = f"{self.base_url}/repos/{owner}/{repo}/contents/{path.lstrip('/')}"
        b64_content = base64.b64encode(content.encode("utf-8")).decode("utf-8")
        payload = {
            "message": commit_message,
            "content": b64_content,
            "branch": branch,
        }
        if sha:
            payload["sha"] = sha

        async with httpx.AsyncClient(timeout=self.timeout) as client:
            resp = await client.put(url, json=payload, headers=self._get_headers(token))
            if resp.status_code not in (200, 201):
                raise GitHubApiException(
                    resp.status_code,
                    f"Failed to put content '{path}': {resp.text}",
                    details={"path": path, "response": resp.text},
                )
            return resp.json(), resp.status_code

    async def get_branch(self, token: str, owner: str, repo: str, branch: str = "main") -> Tuple[Dict[str, Any], int]:
        """Gets branch information including latest commit SHA."""
        url = f"{self.base_url}/repos/{owner}/{repo}/branches/{branch}"
        async with httpx.AsyncClient(timeout=self.timeout) as client:
            resp = await client.get(url, headers=self._get_headers(token))
            if resp.status_code != 200:
                raise GitHubApiException(resp.status_code, f"Failed to verify branch '{branch}': {resp.text}")
            return resp.json(), resp.status_code

    async def delete_repository(self, token: str, owner: str, repo: str) -> bool:
        """Deletes a repository on GitHub."""
        url = f"{self.base_url}/repos/{owner}/{repo}"
        async with httpx.AsyncClient(timeout=self.timeout) as client:
            resp = await client.delete(url, headers=self._get_headers(token))
            if resp.status_code == 404:
                # Already deleted
                return True
            if resp.status_code == 401:
                raise UnauthorizedException("GitHub token expired or missing delete permissions.")
            if resp.status_code not in (204, 200):
                raise GitHubApiException(resp.status_code, f"Failed to delete repository: {resp.text}")
            return True


